"""Одна ручка на все подтверждения: `auto`, `basic`, `debug`.

До этого «спрашивать или нет» и «сколько ждать» решались в четырёх местах
независимо — глобальный тайм-аут обработчика, два собственных окна обзоров
модуля экспериментов, окно вето у наряда на работу, — и решения расходились.
Разбор сохранённых сессий показал, во что это обходится: 34 из 45 истёкших
карточек закончились автоматическим «одобрено», при этом уровень `side_effect`
— самый опасный — оказался единственным с обратным отсчётом, а уровни `read` и
`compute` ждали человека вечно. Предсказать поведение системы по настройкам
было нельзя.

Здесь три режима, и каждый описывается одной фразой:

* ``auto``  — никого не спрашиваем, всё подтверждается сразу. Для
  автоматизированных прогонов, которые некому сопровождать.
* ``basic`` — спрашиваем и ждём человека десять минут; молчание — это ОТКАЗ.
  По умолчанию.
* ``debug`` — спрашиваем и ждём сколько угодно. Нужен, когда проверяешь
  соседние системы (MCP, песочницу) и прогон не должен уехать без тебя.

Молчание не подтверждает ни в одном из трёх. Это и есть главное правило: если
прогон должен идти без человека, для этого есть ``auto``, и он назван вслух —
а «никто не смотрел, значит согласен» было именно тем, что делало работу
непредсказуемой.

Режим читается на каждый вызов, а не при старте: вкладка «Подтверждения» должна
действовать со следующей карточки, а не со следующего перезапуска.
"""
from __future__ import annotations

import logging
import os

logger = logging.getLogger(__name__)

AUTO = "auto"
BASIC = "basic"
DEBUG = "debug"
MODES = (AUTO, BASIC, DEBUG)

#: Сколько ждёт человек в базовом режиме. Десять минут — столько, чтобы успеть
#: прочитать план эксперимента, и не столько, чтобы забытая вкладка держала
#: прогон до утра.
BASIC_WAIT_S = 600.0

_ENV = "HITL__MODE"


def _from_legacy() -> str:
    """Режим, выведенный из старых переменных, когда новой не задано.

    Выводится ТОЛЬКО срок ожидания: неположительный тайм-аут дословно означает
    «ждать сколько угодно», то есть ``debug``.

    `HITL__ENABLED=false` сюда не отображается, хотя соблазн очевиден. Этот
    выключатель снимает колбэки и инструменты нарядов, но два обзора модуля
    экспериментов спрашивают и при нём — так задумано, и так написано в самой
    вкладке «Подтверждения»: «модуль экспериментов спрашивает про эти два даже
    когда выключатель сверху выключен, иначе единственный путь через
    приостановленный план оказался бы скрыт». Вывести из выключателя ``auto``
    значило бы молча утверждать план эксперимента на 7 задач и 230 минут,
    ни разу не показав карточку. ``auto`` надо назвать вслух.
    """
    try:
        from CoScientist.config import get_settings

        if float(get_settings().web.hitl_auto_approve_timeout) <= 0:
            return DEBUG
    except Exception:  # noqa: BLE001 — нечитаемые настройки не меняют режим
        return BASIC
    return BASIC


def hitl_mode() -> str:
    """Действующий режим. `HITL__MODE` побеждает, иначе выводим из старых ручек."""
    said = os.getenv(_ENV, "").strip().lower()
    if said in MODES:
        return said
    if said:
        logger.warning("%s=%r — неизвестный режим, беру %s. Допустимые: %s",
                       _ENV, said, BASIC, ", ".join(MODES))
        return BASIC
    try:
        from CoScientist.config import get_settings

        chosen = str(getattr(get_settings().web, "hitl_mode", "") or "").strip().lower()
        if chosen in MODES:
            return chosen
    except Exception:  # noqa: BLE001
        pass
    return _from_legacy()


def auto_approves() -> bool:
    """Подтверждать не спрашивая — и не рисуя карточку вовсе."""
    return hitl_mode() == AUTO


def wait_seconds() -> float | None:
    """Сколько ждать ответа. `None` — бесконечно.

    В ``auto`` спрашивать некого, но значение возвращается осмысленное на
    случай, если какой-то путь всё же дойдёт до ожидания: ноль секунд, то есть
    немедленный исход.
    """
    mode = hitl_mode()
    if mode == DEBUG:
        return None
    if mode == AUTO:
        return 0.0
    return BASIC_WAIT_S


def silence_approves() -> bool:
    """Никогда. Оставлено функцией, а не константой, чтобы место, которое
    когда-нибудь захочет это изменить, было ровно одно и называлось вслух."""
    return False


def describe() -> str:
    """Одна строка для журнала и для карточки настроек."""
    mode = hitl_mode()
    if mode == AUTO:
        return "auto — подтверждения не запрашиваются"
    if mode == DEBUG:
        return "debug — подтверждения ждут человека без ограничения по времени"
    return f"basic — ожидание {BASIC_WAIT_S:g} с, молчание считается отказом"


__all__ = [
    "AUTO", "BASIC", "DEBUG", "MODES", "BASIC_WAIT_S",
    "auto_approves", "describe", "hitl_mode", "silence_approves", "wait_seconds",
]
